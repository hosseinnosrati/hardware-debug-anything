"""Renode & QEMU Virtual Silicon Simulation Engine.

Enables automated testing and debugging of ARM Cortex-M / RISC-V firmware
without requiring physical target development boards.
"""

from __future__ import annotations
import os
import struct
import subprocess
from dataclasses import dataclass
from typing import Dict, List, Optional, Any


@dataclass
class RenodeProfile:
    board_name: str
    mcu_model: str
    cpu_arch: str
    default_rom_start: int
    default_ram_start: int


PROFILES = {
    "stm32f103": RenodeProfile("STM32F103 (BluePill)", "STM32F103C8", "cortex-m3", 0x08000000, 0x20000000),
    "stm32f4": RenodeProfile("STM32F4 Discovery", "STM32F407VG", "cortex-m4", 0x08000000, 0x20000000),
    "esp32_c3": RenodeProfile("ESP32-C3", "ESP32-C3", "riscv32", 0x42000000, 0x3FC80000),
}


class VirtualSiliconRunner:
    """Orchestrates headless simulation of bare-metal binaries."""

    @classmethod
    def generate_renode_script(
        cls,
        elf_path: str,
        board: str = "stm32f103",
        timeout_sec: float = 5.0,
    ) -> str:
        """Generate automated Renode (.resc) test script."""
        profile = PROFILES.get(board.lower(), PROFILES["stm32f103"])
        norm_path = os.path.abspath(elf_path).replace("\\", "/")

        resc = f"""# Autonomous Renode Simulation Script generated by HDA
using sysbus
mach create "{board}"
machine LoadPlatformDescription @platforms/cpus/{profile.mcu_model.lower()}.repl

showAnalyzer sysbus.usart1
sysbus LoadELF @{norm_path}

# Setup automated monitor hooks
emulation SetGlobalSerialExecution true
cpu StartVector 0x{profile.default_rom_start:08X}

# Execution run
start
"""
        return resc

    @classmethod
    def inspect_arm_vector_table(cls, bin_or_elf_bytes: bytes) -> Dict[str, Any]:
        """Inspect initial SP and Reset Vector from raw ARM Cortex-M binary."""
        if len(bin_or_elf_bytes) < 16:
            return {"status": "ERROR", "integrity": "FAIL", "reason": "Binary too small for vector table."}

        # Vector table format (ARMv7-M):
        # 0x00: Initial Stack Pointer (MSP)
        # 0x04: Reset Handler
        # 0x08: NMI Handler
        # 0x0C: HardFault Handler
        msp, reset_h, nmi_h, hardfault_h = struct.unpack("<4I", bin_or_elf_bytes[:16])

        # Thumb mode requires bit 0 of handler address to be set
        is_thumb = bool(reset_h & 1)
        valid_ram = (msp & 0xFF000000) == 0x20000000 or (msp & 0xFF000000) == 0x10000000
        valid_flash = (reset_h & 0xFF000000) == 0x08000000 or (reset_h & 0xFF000000) == 0x00000000

        return {
            "initial_stack_pointer": f"0x{msp:08X}",
            "reset_handler": f"0x{reset_h:08X}",
            "hardfault_handler": f"0x{hardfault_h:08X}",
            "thumb_mode_set": is_thumb,
            "valid_ram_stack": valid_ram,
            "valid_flash_reset": valid_flash,
            "integrity": "PASS" if (is_thumb and valid_flash) else "SUSPECT",
        }
